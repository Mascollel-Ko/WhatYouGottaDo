NEW_D2 = '삼두근/이두근/대흉근/코어'
PROV = 'USER_APPROVED_OVERHEAD_PRESS_CORRECTION_2026_11_10'


def put(row, col, value):
    ref = f'{col}{row.attrib["r"]}'
    c = next((c for c in row.findall(f'{{{N}}}c') if c.get('r') == ref), None)
    if c is None:
        c = ET.Element(f'{{{N}}}c', {'r': ref})
        # OOXML cells must be in ascending column order.
        def cnum(s):
            v = 0
            for ch in re.match('[A-Z]+', s).group():
                v = v * 26 + ord(ch) - 64
            return v
        index = sum(cnum(e.attrib['r']) < cnum(ref) for e in row.findall(f'{{{N}}}c'))
        row.insert(index, c)
    for child in list(c):
        c.remove(child)
    c.attrib.pop('s', None)
    c.set('t', 'inlineStr')
    ET.SubElement(ET.SubElement(c, f'{{{N}}}is'), f'{{{N}}}t').text = str(value)


def patch_workbook():
    with zipfile.ZipFile(WORKBOOK) as src:
        files = {item.filename: (item, src.read(item.filename)) for item in src.infolist()}
    wb = ET.fromstring(files['xl/workbook.xml'][1])
    rels = ET.fromstring(files['xl/_rels/workbook.xml.rels'][1])
    targets = {}
    for rel in rels.findall(f'{{{P}}}Relationship'):
        p = rel.get('Target', '').lstrip('/')
        targets[rel.get('Id')] = p if p.startswith('xl/') else 'xl/' + p
    sheets = {s.get('name'): targets[s.get(f'{{{R}}}id')]
              for s in wb.findall('.//x:sheets/x:sheet', NS)}
    shared = []
    if 'xl/sharedStrings.xml' in files:
        data = ET.fromstring(files['xl/sharedStrings.xml'][1])
        shared = [''.join((n.text or '') for n in si.findall('.//x:t', NS))
                  for si in data.findall('x:si', NS)]
    updates = {}
    affected_sheets = set()
    for sheet, path in sheets.items():
        if not path.startswith('xl/worksheets/'):
            continue
        tree = ET.fromstring(files[path][1])
        _, cols, data = rows_of(tree, shared)
        columns = {header: col for col, header in cols}
        xmlrows = tree.find('.//x:sheetData', NS).findall(f'{{{N}}}row')[1:]
        assert len(xmlrows) == len(data), sheet
        changed = False
        for record, xmlrow in zip(data, xmlrows):
            change = {}
            if record.get('stableKey', record.get('exerciseStableKey')) == KEY:
                for field in ('exerciseName', 'name', 'familyName'):
                    if field in columns and record.get(field) == OLD_NAME:
                        change[field] = NEW_NAME
                if sheet == '05_IDENTITY_MASTER':
                    change['jointAction'] = (
                        'ELBOW_EXTENSION|ELBOW_FLEXION|SHOULDER_EXTENSION|'
                        'SHOULDER_FLEXION|SCAPULAR_RETRACTION|SCAPULAR_UPWARD_ROTATION'
                    )
                    change['mobilityDemandLevel'] = 'MODERATE'
                if sheet == '09_MOVEMENT_REL':
                    if record.get('relationType') == 'MOVEMENT_PATTERN' and record.get('relationValue') == 'HORIZONTAL_PUSH':
                        change['relationValue'] = 'VERTICAL_PUSH'
                    if record.get('relationType') == 'JOINT_ACTION' and record.get('relationValue') == 'SHOULDER_HORIZONTAL_ADDUCTION':
                        change['relationValue'] = 'SHOULDER_FLEXION'
                if sheet == '10_MUSCLE_REL':
                    if record.get('muscleCode') == 'CHEST':
                        change['muscleRelationType'] = 'SECONDARY'
                        change['coefficient'] = '0.5'
                    if record.get('muscleCode') == 'SHOULDERS':
                        change['muscleRelationType'] = 'PRIMARY'
                        change['coefficient'] = '1'
                if sheet == '29_EXERCISE_BOOTSTRAP':
                    change.update(
                        detail1=NEW_D1, detail2=NEW_D2, description=DESCRIPTION,
                        primaryMuscles='LAT,SHOULDER,OBLIQUE',
                        secondaryMuscles='TRICEPS,BICEPS,CHEST',
                        mobilityDemandLevel='MODERATE',
                        fatigueCategories='LOCAL_MUSCLE,ANTI_ROTATION,GRIP_FOREARM,OVERHEAD_REPETITION',
                        adaptiveBaselineGroups='ANTI_ROTATION,GRIP_FOREARM,SHOULDER_OVERHEAD',
                    )
                if sheet == '18_TRAINING_ROLE':
                    change['notes'] = 'Badminton anti-rotation stability: horizontal cable row with opposite-arm overhead dumbbell press.'
                if sheet == '19_PROGRAM_SLOT':
                    change['notes'] = 'Overhead dumbbell press and contralateral cable row train trunk anti-rotation; not an overhead-swing power claim.'
            if sheet == '30_METADATA_DISPLAY_LABELS':
                current = (record.get('displayField'), record.get('canonicalCode'))
                labels = {
                    ('EXERCISE_DETAIL', OLD_D1): (NEW_D1, NEW_D1, 'Lats / deltoids / obliques'),
                    ('EXERCISE_DETAIL', OLD_D2): (NEW_D2, NEW_D2, 'Triceps / biceps / chest / core'),
                    ('MOVEMENT_SUBTYPE', 'SPLIT_STANCE_CONTRALATERAL_ROW_PRESS'): (
                        'SPLIT_STANCE_CONTRALATERAL_ROW_PRESS',
                        '스플릿 스탠스 반대팔 로우·오버헤드 프레스',
                        'Split-stance cable row and contralateral dumbbell overhead press',
                    ),
                }
                if current in labels:
                    code, ko, en = labels[current]
                    change.update(
                        canonicalCode=code,
                        koreanLabel=ko, koreanShortLabel=ko, koreanFormalLabel=ko,
                        englishLabel=en,
                        koreanDescription='케이블 로우와 반대쪽 덤벨 오버헤드 프레스를 동시에 수행하는 항회전 안정화 훈련',
                    )
            if change:
                unknown = set(change) - set(columns)
                assert not unknown, (sheet, unknown)
                for key, val in change.items():
                    put(xmlrow, columns[key], val)
                changed = True
        if sheet == '09_MOVEMENT_REL':
            assert sum(r.get('exerciseStableKey') == KEY for r in data) == 8
            assert not any(r.get('relationId') == 'MOVEMENT_SPLIT_ROW_PRESS_09' for r in data)
            append(tree, cols, [dict.fromkeys((x for _, x in cols), '') | dict(
                relationId='MOVEMENT_SPLIT_ROW_PRESS_09', exerciseStableKey=KEY,
                exerciseName=NEW_NAME, relationType='JOINT_ACTION',
                relationValue='SCAPULAR_UPWARD_ROTATION', sourceStableKey=KEY,
                status='REVIEW_RECOMMENDED', provenance=PROV,
            )])
            changed = True
        if changed:
            updates[path] = ET.tostring(tree, encoding='utf-8', xml_declaration=True)
            affected_sheets.add(sheet)
    assert {'05_IDENTITY_MASTER','09_MOVEMENT_REL','10_MUSCLE_REL','29_EXERCISE_BOOTSTRAP','30_METADATA_DISPLAY_LABELS'}.issubset(affected_sheets),affected_sheets
    with zipfile.ZipFile(WORKBOOK.with_suffix('.xlsx.tmp'), 'w') as dest:
        for path, (item, raw) in files.items():
            dest.writestr(item, updates.get(path, raw))
    WORKBOOK.with_suffix('.xlsx.tmp').replace(WORKBOOK)
    print('Workbook sheets corrected:', ', '.join(sorted(affected_sheets)))


def patch_source_csv():
    files = [
        ROOT / 'docs/metadata_authority/core_training_classification_review_2026-08-13.csv',
        ROOT / 'docs/metadata_authority/badminton_objective_relations_v2_authority.csv',
        ROOT / 'docs/metadata_authority/metadata_display_inventory.csv',
    ]
    for path in files:
        with path.open(encoding='utf-8-sig', newline='') as source:
            reader = csv.DictReader(source)
            header = reader.fieldnames
            rows = list(reader)
        updated = False
        for row in rows:
            if row.get('stableKey', row.get('exerciseStableKey')) == KEY:
                if row.get('exerciseName') == OLD_NAME:
                    row['exerciseName'] = NEW_NAME
                    updated = True
                if 'classificationReason' in row:
                    row['classificationReason'] = 'Maintains anti-rotation as an arm rows horizontally while the opposite arm presses overhead.'
                    updated = True
                if 'reviewReason' in row and row.get('objectiveId') == 'ANTI_ROTATION':
                    row['reviewReason'] = 'Product-approved direct anti-rotation task during a contralateral cable row and overhead press; not proof of sport-performance improvement.'
                    updated = True
            if path.name == 'metadata_display_inventory.csv':
                pair = (row.get('displayField'), row.get('canonicalCode'))
                options = {
                    ('EXERCISE_DETAIL', OLD_D1): (NEW_D1, NEW_D1, 'Lats / deltoids / obliques'),
                    ('EXERCISE_DETAIL', OLD_D2): (NEW_D2, NEW_D2, 'Triceps / biceps / chest / core'),
                    ('MOVEMENT_SUBTYPE', 'SPLIT_STANCE_CONTRALATERAL_ROW_PRESS'): (
                        'SPLIT_STANCE_CONTRALATERAL_ROW_PRESS',
                        '스플릿 스탠스 반대팔 로우·오버헤드 프레스',
                        'Split-stance cable row and contralateral dumbbell overhead press'),
                }
                if pair in options:
                    code, ko, en = options[pair]
                    row['canonicalCode'], row['currentKoreanLabel'], row['currentEnglishLabel'] = code, ko, en
                    updated = True
        assert updated, path
        with path.open('w', encoding='utf-8-sig', newline='') as out:
            writer = csv.DictWriter(out, fieldnames=header, lineterminator='\n')
            writer.writeheader()
            writer.writerows(rows)
    py = ROOT / 'tools/metadata_authority/analysis_cutover_authority.py'
    source = py.read_text('utf-8')
    for const, path in [
        ('CORE_APPROVED_SHA256', files[0]),
        ('BADMINTON_OBJECTIVE_AUTHORITY_SHA256', files[1])
    ]:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        source, n = re.subn(
            r'('+const+r' = ")[0-9a-f]{64}(")',
            lambda m: m.group(1)+digest+m.group(2), source)
        assert n == 1, const
    py.write_text(source, encoding='utf-8')


if __name__ == '__main__':
    patch_workbook()
    patch_source_csv()
